"""Measure a staged local OCR profile against the synthetic-only benchmark corpus."""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path
from statistics import mean

from reader.ocr.address_ocr import read_address_image
from reader.ocr.engines import get_ocr_engine
from reader.ocr.name_ocr import read_name_image
from tests.ocr_benchmark_cases import SYNTHETIC_OCR_CASES


def _distance(left: str, right: str) -> int:
    row = list(range(len(right) + 1))
    for index, source in enumerate(left, 1):
        next_row = [index]
        for target_index, target in enumerate(right, 1):
            next_row.append(min(next_row[-1] + 1, row[target_index] + 1, row[target_index - 1] + (source != right[target_index - 1])))
        row = next_row
    return row[-1]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--images", type=Path, required=True, help="Directory generated by generate_synthetic_ocr_benchmark.py")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    engine = get_ocr_engine()
    rows: list[dict[str, object]] = []
    for index, case in enumerate(SYNTHETIC_OCR_CASES):
        image = (args.images / f"{index:02d}-{case.name}.png").read_bytes()
        started = time.perf_counter()
        if case.field == "name":
            data = read_name_image(image, engine=engine)
            actual = str(data["name_ocr_candidate"])
        else:
            data, _ = read_address_image(image, engine=engine)
            actual = str(data["address_full_candidate"])
        elapsed_ms = round((time.perf_counter() - started) * 1000, 2)
        rows.append({"case": case.name, "field": case.field, "expected": case.text.replace("\n", ""), "actual": actual, "exact": actual == case.text.replace("\n", ""), "cer": _distance(actual, case.text.replace("\n", "")) / max(1, len(case.text.replace("\n", ""))), "latency_ms": elapsed_ms})
    address_rows = [row for row in rows if row["field"] == "address"]
    output = {
        "engine": getattr(engine, "model_name", "unavailable"),
        "model_profile": "ppocrv6",
        "exact_line_accuracy": sum(bool(row["exact"]) for row in rows) / len(rows),
        "character_error_rate": sum(float(row["cer"]) for row in rows) / len(rows),
        "address_component_preservation": sum("府" in str(row["actual"]) or "県" in str(row["actual"]) for row in address_rows) / len(address_rows),
        "name_latency_ms": [row["latency_ms"] for row in rows if row["field"] == "name"],
        "address_latency_ms": [row["latency_ms"] for row in address_rows],
        "name_latency_mean_ms": round(mean(row["latency_ms"] for row in rows if row["field"] == "name"), 2),
        "address_latency_mean_ms": round(mean(row["latency_ms"] for row in address_rows), 2),
        "rows": rows,
    }
    args.output.write_text(json.dumps(output, ensure_ascii=False, indent=2), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
